import { useMemo, useState } from 'react';
import { Download, Plus, Trash2 } from 'lucide-react';
import { SITE } from '@/data/site';

interface Guest {
  id: string;
  name: string;
}

interface Table {
  id: number;
  name: string;
  capacity: number;
  guests: Guest[];
}

export default function SeatingPlannerTool() {
  const [guestText, setGuestText] = useState('');
  const [guests, setGuests] = useState<Guest[]>([]);
  const [tables, setTables] = useState<Table[]>([{ id: 1, name: 'Table 1 (Top Table)', capacity: 10, guests: [] }]);
  const [notice, setNotice] = useState('');

  const processGuestList = () => {
    const names = guestText
      .split('\n')
      .map((s) => s.trim())
      .filter(Boolean);
    const parsed = names.map((name, idx) => ({ id: `g-${Date.now()}-${idx}`, name }));
    setGuests(parsed);
    setNotice(`${parsed.length} guests loaded into unassigned list.`);
  };

  const unassignedGuests = useMemo(() => {
    const assigned = new Set(tables.flatMap((t) => t.guests.map((g) => g.id)));
    return guests.filter((g) => !assigned.has(g.id));
  }, [guests, tables]);

  const assignGuest = (guestId: string, tableId: number) => {
    if (!guestId) return;
    const guest = unassignedGuests.find((g) => g.id === guestId);
    if (!guest) return;
    setTables((prev) =>
      prev.map((t) =>
        t.id === tableId && t.guests.length < t.capacity ? { ...t, guests: [...t.guests, guest] } : t
      )
    );
  };

  const unassignGuest = (guestId: string, tableId: number) => {
    setTables((prev) =>
      prev.map((t) => (t.id === tableId ? { ...t, guests: t.guests.filter((g) => g.id !== guestId) } : t))
    );
  };

  const exportCSV = () => {
    const lines = ['Table Name,Guest Name'];
    tables.forEach((t) => t.guests.forEach((g) => lines.push(`"${t.name}","${g.name}"`)));
    if (unassignedGuests.length > 0) {
      unassignedGuests.forEach((g) => lines.push(`"Unassigned","${g.name}"`));
    }
    lines.push('', `Generated by ${SITE.legalName} | ${SITE.phoneDisplay} | ${SITE.email}`);
    const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'seating_plan.csv';
    a.click();
    URL.revokeObjectURL(url);
    setNotice('Seating plan exported to CSV!');
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-8 items-start">
      <div className="space-y-6">
        <div className="rounded-2xl border border-salwah-gold/20 bg-[#12151e] p-6 space-y-3">
          <h2 className="font-serif text-xl font-bold text-salwah-gold">1. Paste Guest Names</h2>
          <textarea
            value={guestText}
            onChange={(e) => setGuestText(e.target.value)}
            rows={8}
            placeholder="One guest name per line..."
            className="w-full rounded-lg border border-salwah-gold/25 bg-black/60 p-3 text-sm text-white resize-none"
          />
          <button
            type="button"
            onClick={processGuestList}
            className="w-full rounded-xl bg-salwah-gold py-2.5 text-sm font-bold text-black hover:bg-salwah-gold-light transition cursor-pointer"
          >
            Load Guest List
          </button>
        </div>

        <div className="rounded-2xl border border-salwah-gold/20 bg-[#12151e] p-6">
          <h3 className="font-serif text-lg font-bold text-salwah-gold mb-3">
            Unassigned ({unassignedGuests.length})
          </h3>
          <div className="space-y-1.5 max-h-72 overflow-y-auto text-sm">
            {unassignedGuests.length === 0 ? (
              <p className="text-gray-400 text-xs">No unassigned guests remaining.</p>
            ) : (
              unassignedGuests.map((g) => (
                <div key={g.id} className="rounded-md bg-black/50 px-3 py-1.5 text-gray-200">
                  {g.name}
                </div>
              ))
            )}
          </div>
        </div>
      </div>

      <div className="lg:col-span-2 rounded-2xl border border-salwah-gold/20 bg-[#12151e] p-6 space-y-5">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <h2 className="font-serif text-2xl font-bold text-salwah-gold">2. Tables &amp; Seat Assignments</h2>
          <div className="flex gap-2">
            <button
              type="button"
              onClick={() =>
                setTables((prev) => [
                  ...prev,
                  { id: Date.now(), name: `Table ${prev.length + 1}`, capacity: 10, guests: [] },
                ])
              }
              className="inline-flex items-center gap-1.5 rounded-lg border border-salwah-gold/50 px-3.5 py-2 text-xs font-bold text-salwah-gold hover:bg-salwah-gold hover:text-black transition cursor-pointer"
            >
              <Plus className="h-4 w-4" /> Add Table
            </button>
            <button
              type="button"
              onClick={exportCSV}
              className="inline-flex items-center gap-1.5 rounded-lg bg-salwah-gold px-3.5 py-2 text-xs font-bold text-black hover:bg-salwah-gold-light transition cursor-pointer"
            >
              <Download className="h-4 w-4" /> Export CSV
            </button>
          </div>
        </div>

        <div className="space-y-4">
          {tables.map((table) => (
            <div key={table.id} className="rounded-xl border border-white/15 bg-black/50 p-4 space-y-3">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <input
                  value={table.name}
                  onChange={(e) =>
                    setTables((prev) => prev.map((t) => (t.id === table.id ? { ...t, name: e.target.value } : t)))
                  }
                  className="rounded-md border border-salwah-gold/25 bg-black/70 px-3 py-1.5 text-sm font-bold text-white"
                />
                <div className="flex items-center gap-2 text-xs text-gray-300">
                  <label>Seats:</label>
                  <input
                    type="number"
                    min={1}
                    value={table.capacity}
                    onChange={(e) =>
                      setTables((prev) =>
                        prev.map((t) => (t.id === table.id ? { ...t, capacity: Math.max(1, Number(e.target.value)) } : t))
                      )
                    }
                    className="w-16 rounded-md border border-salwah-gold/25 bg-black/70 px-2 py-1 text-white"
                  />
                  <button
                    type="button"
                    onClick={() => setTables((prev) => prev.filter((t) => t.id !== table.id))}
                    className="text-red-400 hover:text-red-300 cursor-pointer"
                    aria-label="Delete table"
                  >
                    <Trash2 className="h-4 w-4" />
                  </button>
                </div>
              </div>

              <select
                value=""
                disabled={table.guests.length >= table.capacity || unassignedGuests.length === 0}
                onChange={(e) => assignGuest(e.target.value, table.id)}
                className="w-full rounded-md border border-salwah-gold/25 bg-black/70 px-3 py-2 text-sm text-white disabled:opacity-50"
              >
                <option value="">Assign a guest to {table.name}...</option>
                {unassignedGuests.map((g) => (
                  <option key={g.id} value={g.id} className="bg-[#12151e]">{g.name}</option>
                ))}
              </select>

              {table.guests.length > 0 && (
                <div className="space-y-1">
                  {table.guests.map((g) => (
                    <div key={g.id} className="flex items-center justify-between rounded bg-white/5 px-3 py-1.5 text-sm">
                      <span>{g.name}</span>
                      <button
                        type="button"
                        onClick={() => unassignGuest(g.id, table.id)}
                        className="text-xs text-amber-300 hover:underline cursor-pointer"
                      >
                        Remove
                      </button>
                    </div>
                  ))}
                </div>
              )}

              <p className="text-right text-xs text-gray-400">
                {table.guests.length} / {table.capacity} seats filled
              </p>
            </div>
          ))}
        </div>

        {notice && <p className="text-sm text-salwah-gold">{notice}</p>}
      </div>
    </div>
  );
}
