import { useMemo, useState } from 'react';
import { Download, FileText, Plus, Trash2 } from 'lucide-react';
import autoTable from 'jspdf-autotable';
import { generatePdfWithHeaderFooter } from '@/lib/pdfUtils';
import { SITE } from '@/data/site';

interface BudgetRow {
  id: number;
  name: string;
  cost: number;
  enabled: boolean;
}

const gbp = (v: number) =>
  new Intl.NumberFormat('en-GB', { style: 'currency', currency: 'GBP' }).format(v);

export default function BudgetCalculatorTool() {
  const [guestCount, setGuestCount] = useState(200);
  const [perHeadItems, setPerHeadItems] = useState<BudgetRow[]>([
    { id: 1, name: 'Halal Catering (Gold Package)', cost: 40, enabled: true },
  ]);
  const [fixedItems, setFixedItems] = useState<BudgetRow[]>([
    { id: 1, name: 'Venue Hire', cost: 5000, enabled: true },
    { id: 2, name: 'Wedding Stage Decor', cost: 2500, enabled: true },
    { id: 3, name: 'Photography & Film', cost: 1800, enabled: true },
  ]);
  const [vat, setVat] = useState(20);
  const [serviceCharge, setServiceCharge] = useState(0);
  const [notice, setNotice] = useState('');

  const updateRow = (
    type: 'per-head' | 'fixed',
    id: number,
    patch: Partial<BudgetRow>
  ) => {
    const setter = type === 'per-head' ? setPerHeadItems : setFixedItems;
    setter((rows) => rows.map((r) => (r.id === id ? { ...r, ...patch } : r)));
  };

  const addRow = (type: 'per-head' | 'fixed') => {
    const setter = type === 'per-head' ? setPerHeadItems : setFixedItems;
    setter((rows) => [...rows, { id: Date.now(), name: '', cost: 0, enabled: true }]);
  };

  const removeRow = (type: 'per-head' | 'fixed', id: number) => {
    const setter = type === 'per-head' ? setPerHeadItems : setFixedItems;
    setter((rows) => rows.filter((r) => r.id !== id));
  };

  const totals = useMemo(() => {
    const perHeadTotal = perHeadItems.reduce((acc, i) => (i.enabled ? acc + Number(i.cost || 0) : acc), 0);
    const fixedTotal = fixedItems.reduce((acc, i) => (i.enabled ? acc + Number(i.cost || 0) : acc), 0);
    const subtotal = perHeadTotal * guestCount + fixedTotal;
    const vatAmount = subtotal * (vat / 100);
    const serviceChargeAmount = subtotal * (serviceCharge / 100);
    const grandTotal = subtotal + vatAmount + serviceChargeAmount;
    return { subtotal, vatAmount, serviceChargeAmount, grandTotal };
  }, [perHeadItems, fixedItems, guestCount, vat, serviceCharge]);

  const exportCSV = () => {
    const lines = ['Category,Item,Unit Cost,Enabled,Total'];
    perHeadItems.forEach((i) =>
      lines.push(`Per Head,"${i.name}",${i.cost},${i.enabled},${i.enabled ? i.cost * guestCount : 0}`)
    );
    fixedItems.forEach((i) =>
      lines.push(`Fixed,"${i.name}",${i.cost},${i.enabled},${i.enabled ? i.cost : 0}`)
    );
    lines.push(
      '',
      `Subtotal,,,,${totals.subtotal}`,
      `VAT (${vat}%),,,,${totals.vatAmount}`,
      `Service Charge (${serviceCharge}%),,,,${totals.serviceChargeAmount}`,
      `Grand Total,,,,${totals.grandTotal}`,
      '',
      `Generated by ${SITE.legalName} | ${SITE.phoneDisplay} | ${SITE.email}`
    );
    const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'wedding_budget.csv';
    a.click();
    URL.revokeObjectURL(url);
    setNotice('CSV budget exported.');
  };

  const exportPDF = () => {
    const doc = generatePdfWithHeaderFooter('Wedding Budget Estimate', (pdf) => {
      pdf.setFontSize(11);
      pdf.setTextColor(100);
      pdf.text(`Estimated Guest Count: ${guestCount}`, 14, 38);

      autoTable(pdf, {
        startY: 44,
        head: [['Per-Head Items', 'Cost / Guest', 'Included', 'Total']],
        body: perHeadItems.map((i) => [
          i.name,
          gbp(i.cost),
          i.enabled ? 'Yes' : 'No',
          gbp(i.enabled ? i.cost * guestCount : 0),
        ]),
        headStyles: { fillColor: [212, 175, 55], textColor: [0, 0, 0] },
      });

      const yAfterPerHead = (pdf as unknown as { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY ?? 70;
      autoTable(pdf, {
        startY: yAfterPerHead + 8,
        head: [['Fixed Cost Items', 'Cost', 'Included', 'Total']],
        body: fixedItems.map((i) => [i.name, gbp(i.cost), i.enabled ? 'Yes' : 'No', gbp(i.enabled ? i.cost : 0)]),
        headStyles: { fillColor: [212, 175, 55], textColor: [0, 0, 0] },
      });

      const yAfterFixed = (pdf as unknown as { lastAutoTable?: { finalY?: number } }).lastAutoTable?.finalY ?? 110;
      autoTable(pdf, {
        startY: yAfterFixed + 8,
        body: [
          ['Subtotal', gbp(totals.subtotal)],
          [`VAT (${vat}%)`, gbp(totals.vatAmount)],
          [`Service Charge (${serviceCharge}%)`, gbp(totals.serviceChargeAmount)],
          ['Grand Total', gbp(totals.grandTotal)],
        ],
        theme: 'plain',
        styles: { fontSize: 12 },
        columnStyles: { 0: { fontStyle: 'bold' } },
      });
    });

    doc.save('wedding_budget.pdf');
    setNotice('PDF budget exported.');
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-8 items-start">
      <div className="lg:col-span-2 space-y-6">
        {(
          [
            { key: 'per-head', title: 'Per-Head Costs (£ per guest)', rows: perHeadItems },
            { key: 'fixed', title: 'Fixed Wedding Costs (£ total)', rows: fixedItems },
          ] as const
        ).map((group) => (
          <div key={group.key} className="rounded-2xl border border-salwah-gold/20 bg-[#12151e] p-6 space-y-3">
            <h2 className="font-serif text-2xl font-bold text-salwah-gold">{group.title}</h2>
            {group.rows.map((item) => (
              <div key={item.id} className="grid grid-cols-12 gap-2 items-center">
                <input
                  type="checkbox"
                  checked={item.enabled}
                  onChange={(e) => updateRow(group.key, item.id, { enabled: e.target.checked })}
                  className="col-span-1 h-5 w-5 accent-[#f6df91]"
                  aria-label="Enable item"
                />
                <input
                  type="text"
                  value={item.name}
                  onChange={(e) => updateRow(group.key, item.id, { name: e.target.value })}
                  placeholder="Item Name"
                  className="col-span-6 rounded-lg border border-salwah-gold/25 bg-black/60 px-3 py-2 text-sm text-white"
                />
                <input
                  type="number"
                  value={item.cost}
                  onChange={(e) => updateRow(group.key, item.id, { cost: Number(e.target.value) })}
                  placeholder="0"
                  className="col-span-3 rounded-lg border border-salwah-gold/25 bg-black/60 px-3 py-2 text-sm text-white text-right"
                />
                <button
                  type="button"
                  onClick={() => removeRow(group.key, item.id)}
                  aria-label="Remove item"
                  className="col-span-2 flex justify-center py-2 text-red-400 hover:text-red-300 cursor-pointer"
                >
                  <Trash2 className="h-4 w-4" />
                </button>
              </div>
            ))}
            <button
              type="button"
              onClick={() => addRow(group.key)}
              className="inline-flex items-center gap-2 rounded-lg border border-salwah-gold/40 px-4 py-2 text-sm font-semibold text-salwah-gold hover:bg-salwah-gold hover:text-black transition cursor-pointer"
            >
              <Plus className="h-4 w-4" /> Add Item
            </button>
          </div>
        ))}
      </div>

      <div className="rounded-2xl border border-salwah-gold/30 bg-[#12151e] p-6 lg:sticky lg:top-28 space-y-4">
        <h2 className="font-serif text-2xl font-bold text-salwah-gold">Budget Summary</h2>
        <div>
          <label className="block text-xs uppercase tracking-wider text-gray-400 mb-1">Guest Count</label>
          <input
            type="number"
            min={1}
            value={guestCount}
            onChange={(e) => setGuestCount(Math.max(1, Number(e.target.value)))}
            className="w-full rounded-lg border border-salwah-gold/25 bg-black/60 px-3 py-2.5 text-white"
          />
        </div>
        <div className="grid grid-cols-2 gap-3">
          <div>
            <label className="block text-xs uppercase tracking-wider text-gray-400 mb-1">VAT (%)</label>
            <input
              type="number"
              min={0}
              value={vat}
              onChange={(e) => setVat(Number(e.target.value))}
              className="w-full rounded-lg border border-salwah-gold/25 bg-black/60 px-3 py-2 text-white"
            />
          </div>
          <div>
            <label className="block text-xs uppercase tracking-wider text-gray-400 mb-1">Service (%)</label>
            <input
              type="number"
              min={0}
              value={serviceCharge}
              onChange={(e) => setServiceCharge(Number(e.target.value))}
              className="w-full rounded-lg border border-salwah-gold/25 bg-black/60 px-3 py-2 text-white"
            />
          </div>
        </div>
        <div className="border-t border-white/10 pt-4 space-y-2 text-sm">
          <div className="flex justify-between"><span className="text-gray-300">Subtotal:</span><span>{gbp(totals.subtotal)}</span></div>
          <div className="flex justify-between"><span className="text-gray-300">VAT:</span><span>{gbp(totals.vatAmount)}</span></div>
          <div className="flex justify-between"><span className="text-gray-300">Service Charge:</span><span>{gbp(totals.serviceChargeAmount)}</span></div>
          <div className="flex justify-between font-bold text-xl text-salwah-gold pt-3 border-t border-salwah-gold/20">
            <span>Grand Total:</span>
            <span>{gbp(totals.grandTotal)}</span>
          </div>
        </div>
        <div className="grid grid-cols-2 gap-3 pt-2">
          <button type="button" onClick={exportCSV} className="inline-flex items-center justify-center gap-1.5 rounded-xl border border-salwah-gold/50 py-2.5 text-sm font-bold text-salwah-gold hover:bg-salwah-gold hover:text-black transition cursor-pointer">
            <Download className="h-4 w-4" /> CSV
          </button>
          <button type="button" onClick={exportPDF} className="inline-flex items-center justify-center gap-1.5 rounded-xl bg-salwah-gold py-2.5 text-sm font-bold text-black hover:bg-salwah-gold-light transition cursor-pointer">
            <FileText className="h-4 w-4" /> PDF
          </button>
        </div>
        {notice && <p className="text-xs text-salwah-gold text-center">{notice}</p>}
      </div>
    </div>
  );
}
