import { useMemo, useState } from 'react';
import { Download, Plus, Trash2 } from 'lucide-react';
import { SITE } from '@/data/site';

interface GuestRow {
  id: number;
  name: string;
  status: 'Pending' | 'Attending' | 'Not Attending';
  diet: string;
}

const OPTIONS: GuestRow['status'][] = ['Pending', 'Attending', 'Not Attending'];

export default function RsvpTrackerTool() {
  const [guests, setGuests] = useState<GuestRow[]>([
    { id: 1, name: 'Auntie & Uncle Khan', status: 'Attending', diet: 'Halal' },
    { id: 2, name: 'Priya Sharma', status: 'Pending', diet: 'Vegetarian' },
  ]);
  const [draft, setDraft] = useState<Omit<GuestRow, 'id'>>({ name: '', status: 'Pending', diet: '' });
  const [notice, setNotice] = useState('');

  const addGuest = () => {
    if (!draft.name.trim()) return;
    setGuests((prev) => [...prev, { ...draft, name: draft.name.trim(), id: Date.now() }]);
    setDraft({ name: '', status: 'Pending', diet: '' });
  };

  const stats = useMemo(
    () => ({
      total: guests.length,
      attending: guests.filter((g) => g.status === 'Attending').length,
      pending: guests.filter((g) => g.status === 'Pending').length,
      declined: guests.filter((g) => g.status === 'Not Attending').length,
      dietary: guests.filter((g) => g.diet.trim() !== '').length,
    }),
    [guests]
  );

  const exportCSV = () => {
    const lines = ['Name,RSVP Status,Dietary Needs'];
    guests.forEach((g) => lines.push(`"${g.name}","${g.status}","${g.diet}"`));
    lines.push('', `Generated by ${SITE.legalName} | ${SITE.phoneDisplay} | ${SITE.email}`);
    const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'rsvp_dietary_tracker.csv';
    a.click();
    URL.revokeObjectURL(url);
    setNotice('RSVP list exported to CSV!');
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-8 items-start">
      <div className="lg:col-span-2 rounded-2xl border border-salwah-gold/20 bg-[#12151e] p-6 overflow-x-auto">
        <h2 className="font-serif text-2xl font-bold text-salwah-gold mb-4">Guest List</h2>
        <table className="w-full min-w-[560px] text-sm">
          <thead>
            <tr className="border-b border-salwah-gold/25 text-left text-gray-300">
              <th className="p-2">Name</th>
              <th className="p-2">Status</th>
              <th className="p-2">Dietary Needs</th>
              <th className="p-2 text-center">Action</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-white/10">
            {guests.map((g) => (
              <tr key={g.id}>
                <td className="p-2">
                  <input
                    value={g.name}
                    onChange={(e) => setGuests((prev) => prev.map((x) => (x.id === g.id ? { ...x, name: e.target.value } : x)))}
                    className="w-full rounded-md border border-salwah-gold/20 bg-black/60 px-2.5 py-1.5 text-white"
                  />
                </td>
                <td className="p-2">
                  <select
                    value={g.status}
                    onChange={(e) =>
                      setGuests((prev) =>
                        prev.map((x) => (x.id === g.id ? { ...x, status: e.target.value as GuestRow['status'] } : x))
                      )
                    }
                    className="w-full rounded-md border border-salwah-gold/20 bg-black/60 px-2.5 py-1.5 text-white"
                  >
                    {OPTIONS.map((o) => (
                      <option key={o} value={o} className="bg-[#12151e]">{o}</option>
                    ))}
                  </select>
                </td>
                <td className="p-2">
                  <input
                    value={g.diet}
                    onChange={(e) => setGuests((prev) => prev.map((x) => (x.id === g.id ? { ...x, diet: e.target.value } : x)))}
                    className="w-full rounded-md border border-salwah-gold/20 bg-black/60 px-2.5 py-1.5 text-white"
                  />
                </td>
                <td className="p-2 text-center">
                  <button type="button" onClick={() => setGuests((prev) => prev.filter((x) => x.id !== g.id))} className="text-red-400 hover:text-red-300 cursor-pointer" aria-label="Remove guest">
                    <Trash2 className="h-4 w-4 inline" />
                  </button>
                </td>
              </tr>
            ))}
            <tr>
              <td className="p-2">
                <input
                  value={draft.name}
                  onChange={(e) => setDraft({ ...draft, name: e.target.value })}
                  placeholder="Add Guest Name"
                  className="w-full rounded-md border border-salwah-gold/30 bg-black/60 px-2.5 py-1.5 text-white"
                />
              </td>
              <td className="p-2">
                <select
                  value={draft.status}
                  onChange={(e) => setDraft({ ...draft, status: e.target.value as GuestRow['status'] })}
                  className="w-full rounded-md border border-salwah-gold/30 bg-black/60 px-2.5 py-1.5 text-white"
                >
                  {OPTIONS.map((o) => (
                    <option key={o} value={o} className="bg-[#12151e]">{o}</option>
                  ))}
                </select>
              </td>
              <td className="p-2">
                <input
                  value={draft.diet}
                  onChange={(e) => setDraft({ ...draft, diet: e.target.value })}
                  placeholder="e.g. Vegan, Nut Allergy"
                  className="w-full rounded-md border border-salwah-gold/30 bg-black/60 px-2.5 py-1.5 text-white"
                />
              </td>
              <td className="p-2 text-center">
                <button type="button" onClick={addGuest} className="inline-flex h-8 w-8 items-center justify-center rounded-lg bg-salwah-gold text-black cursor-pointer" aria-label="Add guest">
                  <Plus className="h-4 w-4" />
                </button>
              </td>
            </tr>
          </tbody>
        </table>
      </div>

      <div className="rounded-2xl border border-salwah-gold/30 bg-[#12151e] p-6 lg:sticky lg:top-28 space-y-4">
        <h2 className="font-serif text-2xl font-bold text-salwah-gold">Summary</h2>
        <div className="space-y-2 text-sm">
          <div className="flex justify-between"><span className="text-gray-300">Total Guests:</span><strong className="text-white">{stats.total}</strong></div>
          <div className="flex justify-between"><span className="text-gray-300">Attending:</span><strong className="text-emerald-400">{stats.attending}</strong></div>
          <div className="flex justify-between"><span className="text-gray-300">Pending:</span><strong className="text-amber-300">{stats.pending}</strong></div>
          <div className="flex justify-between"><span className="text-gray-300">Not Attending:</span><strong className="text-red-400">{stats.declined}</strong></div>
          <div className="flex justify-between"><span className="text-gray-300">Dietary Notes:</span><strong className="text-salwah-gold">{stats.dietary}</strong></div>
        </div>
        <button type="button" onClick={exportCSV} className="w-full inline-flex items-center justify-center gap-2 rounded-xl bg-salwah-gold py-3 text-sm font-bold text-black hover:bg-salwah-gold-light transition cursor-pointer">
          <Download className="h-4 w-4" /> Export CSV
        </button>
        {notice && <p className="text-xs text-salwah-gold text-center">{notice}</p>}
      </div>
    </div>
  );
}
