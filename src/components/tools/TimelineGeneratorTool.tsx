import { useState } from 'react';
import { Download } from 'lucide-react';

export default function TimelineGeneratorTool() {
  const [eventDate, setEventDate] = useState(new Date().toISOString().split('T')[0]);
  const [startTime, setStartTime] = useState('14:00');
  const [bufferTime, setBufferTime] = useState(30);
  const [photoTime, setPhotoTime] = useState(60);
  const [receptionTime, setReceptionTime] = useState(120);
  const [notice, setNotice] = useState('');

  const generateICS = () => {
    const fmt = (d: Date) => d.toISOString().replace(/-|:|\.\d\d\d/g, '');
    let cursor = new Date(`${eventDate}T${startTime}:00`);
    const pushEvent = (title: string, mins: number) => {
      const start = new Date(cursor);
      cursor = new Date(cursor.getTime() + mins * 60000);
      return { title, start, end: new Date(cursor) };
    };

    const events = [
      pushEvent('Guest Arrival & Welcome Mocktails', 30),
      pushEvent('Nikah / Wedding Ceremony', 60),
      pushEvent('Mingle & Refreshments', bufferTime),
      pushEvent('Couple & Family Portraits', photoTime),
      pushEvent('Grand Reception & Halal Dinner Service', receptionTime),
    ];

    let ics = 'BEGIN:VCALENDAR\nVERSION:2.0\nPRODID:-//SalwahEvents//WeddingTimeline//EN\n';
    events.forEach((ev, idx) => {
      ics += `BEGIN:VEVENT\nUID:${Date.now()}-${idx}@salwahevents.com\nDTSTAMP:${fmt(new Date())}\nDTSTART:${fmt(ev.start)}\nDTEND:${fmt(ev.end)}\nSUMMARY:${ev.title}\nDESCRIPTION:Generated by Salwah Events and Catering Timeline Tool\nEND:VEVENT\n`;
    });
    ics += 'END:VCALENDAR';

    const blob = new Blob([ics], { type: 'text/calendar;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'salwah_wedding_timeline.ics';
    a.click();
    URL.revokeObjectURL(url);
    setNotice('Calendar .ics timeline downloaded!');
  };

  return (
    <div className="rounded-2xl border border-salwah-gold/25 bg-[#12151e] p-6 sm:p-8 space-y-6">
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        <div>
          <label className="block text-xs font-semibold uppercase tracking-wider text-salwah-gold mb-1.5">Event Date</label>
          <input type="date" value={eventDate} onChange={(e) => setEventDate(e.target.value)} className="w-full rounded-lg border border-salwah-gold/30 bg-black/60 px-3.5 py-2.5 text-white [color-scheme:dark]" />
        </div>
        <div>
          <label className="block text-xs font-semibold uppercase tracking-wider text-salwah-gold mb-1.5">Guest Arrival Time</label>
          <input type="time" value={startTime} onChange={(e) => setStartTime(e.target.value)} className="w-full rounded-lg border border-salwah-gold/30 bg-black/60 px-3.5 py-2.5 text-white [color-scheme:dark]" />
        </div>
        <div>
          <label className="block text-xs font-semibold uppercase tracking-wider text-salwah-gold mb-1.5">Buffer / Mingle (minutes)</label>
          <input type="number" min={0} value={bufferTime} onChange={(e) => setBufferTime(Number(e.target.value))} className="w-full rounded-lg border border-salwah-gold/30 bg-black/60 px-3.5 py-2.5 text-white" />
        </div>
        <div>
          <label className="block text-xs font-semibold uppercase tracking-wider text-salwah-gold mb-1.5">Photo Session (minutes)</label>
          <input type="number" min={0} value={photoTime} onChange={(e) => setPhotoTime(Number(e.target.value))} className="w-full rounded-lg border border-salwah-gold/30 bg-black/60 px-3.5 py-2.5 text-white" />
        </div>
        <div className="md:col-span-2">
          <label className="block text-xs font-semibold uppercase tracking-wider text-salwah-gold mb-1.5">Reception &amp; Halal Dinner (minutes)</label>
          <input type="number" min={30} value={receptionTime} onChange={(e) => setReceptionTime(Number(e.target.value))} className="w-full rounded-lg border border-salwah-gold/30 bg-black/60 px-3.5 py-2.5 text-white" />
        </div>
      </div>

      <button type="button" onClick={generateICS} className="w-full inline-flex items-center justify-center gap-2 rounded-xl bg-salwah-gold py-4 text-base font-bold text-black hover:bg-salwah-gold-light transition cursor-pointer">
        <Download className="h-5 w-5" /> Generate &amp; Download .ics Calendar File
      </button>
      {notice && <p className="text-center text-sm text-salwah-gold">{notice}</p>}
    </div>
  );
}
