import { useMemo, useState } from 'react';
import { Download, Plus, Trash2 } from 'lucide-react';
import { SITE } from '@/data/site';

interface VendorRow {
  id: number;
  name: string;
  food: number;
  reliability: number;
  communication: number;
  flexibility: number;
  price: number;
}

const CRITERIA = ['food', 'reliability', 'communication', 'flexibility'] as const;

export default function VendorScorecardTool() {
  const [vendors, setVendors] = useState<VendorRow[]>([
    { id: 1, name: 'Caterer A', food: 5, reliability: 5, communication: 5, flexibility: 4, price: 7000 },
    { id: 2, name: 'Caterer B', food: 4, reliability: 4, communication: 4, flexibility: 3, price: 6500 },
  ]);
  const [weights, setWeights] = useState({
    food: 0.3,
    reliability: 0.25,
    communication: 0.2,
    flexibility: 0.15,
    price: 0.1,
  });
  const [notice, setNotice] = useState('');

  const scored = useMemo(() => {
    const prices = vendors.map((v) => v.price).filter((p) => p > 0);
    const minPrice = prices.length ? Math.min(...prices) : 0;
    const maxPrice = prices.length ? Math.max(...prices) : 0;

    return vendors
      .map((v) => {
        let priceScore = 3;
        if (maxPrice > minPrice && v.price > 0) {
          priceScore = 1 + 4 * (1 - (v.price - minPrice) / (maxPrice - minPrice));
        } else if (prices.length === 1 && v.price > 0) {
          priceScore = 5;
        }
        const total =
          v.food * weights.food +
          v.reliability * weights.reliability +
          v.communication * weights.communication +
          v.flexibility * weights.flexibility +
          priceScore * weights.price;
        return { ...v, priceScore: priceScore.toFixed(2), totalScore: total.toFixed(2) };
      })
      .sort((a, b) => Number(b.totalScore) - Number(a.totalScore));
  }, [vendors, weights]);

  const totalWeight = Object.values(weights).reduce((s, w) => s + w, 0);

  const exportCSV = () => {
    const lines = ['Vendor,Food,Reliability,Communication,Flexibility,Price,Total Score'];
    scored.forEach((v) =>
      lines.push(`"${v.name}",${v.food},${v.reliability},${v.communication},${v.flexibility},${v.price},${v.totalScore}`)
    );
    lines.push('', `Generated by ${SITE.legalName} | ${SITE.phoneDisplay} | ${SITE.email}`);
    const blob = new Blob([lines.join('\n')], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'vendor_scorecard.csv';
    a.click();
    URL.revokeObjectURL(url);
    setNotice('Vendor scorecard exported to CSV!');
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-8 items-start">
      <div className="lg:col-span-2 rounded-2xl border border-salwah-gold/20 bg-[#12151e] p-6 overflow-x-auto">
        <h2 className="font-serif text-2xl font-bold text-salwah-gold mb-4">Compare Suppliers (1–5)</h2>
        <table className="w-full min-w-[700px] text-sm">
          <thead>
            <tr className="border-b border-salwah-gold/25 text-left text-gray-300">
              <th className="p-2">Vendor</th>
              {CRITERIA.map((c) => <th key={c} className="p-2 capitalize">{c}</th>)}
              <th className="p-2">Quote (£)</th>
              <th className="p-2">Score</th>
              <th className="p-2"></th>
            </tr>
          </thead>
          <tbody className="divide-y divide-white/10">
            {scored.map((v) => (
              <tr key={v.id}>
                <td className="p-2">
                  <input value={v.name} onChange={(e) => setVendors((p) => p.map((x) => (x.id === v.id ? { ...x, name: e.target.value } : x)))} className="w-36 rounded border border-salwah-gold/25 bg-black/60 px-2 py-1 text-white" />
                </td>
                {CRITERIA.map((c) => (
                  <td key={c} className="p-2">
                    <input type="number" min={1} max={5} value={v[c]} onChange={(e) => setVendors((p) => p.map((x) => (x.id === v.id ? { ...x, [c]: Number(e.target.value) } : x)))} className="w-14 rounded border border-salwah-gold/25 bg-black/60 px-2 py-1 text-white" />
                  </td>
                ))}
                <td className="p-2">
                  <input type="number" min={0} value={v.price} onChange={(e) => setVendors((p) => p.map((x) => (x.id === v.id ? { ...x, price: Number(e.target.value) } : x)))} className="w-24 rounded border border-salwah-gold/25 bg-black/60 px-2 py-1 text-white" />
                </td>
                <td className="p-2 font-bold text-salwah-gold text-base">{v.totalScore}</td>
                <td className="p-2">
                  <button type="button" onClick={() => setVendors((p) => p.filter((x) => x.id !== v.id))} className="text-red-400 hover:text-red-300 cursor-pointer" aria-label="Remove vendor">
                    <Trash2 className="h-4 w-4" />
                  </button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        <div className="flex flex-wrap gap-3 mt-4">
          <button type="button" onClick={() => setVendors((p) => [...p, { id: Date.now(), name: '', food: 3, reliability: 3, communication: 3, flexibility: 3, price: 0 }])} className="inline-flex items-center gap-1.5 rounded-lg border border-salwah-gold/50 px-4 py-2 text-xs font-bold text-salwah-gold hover:bg-salwah-gold hover:text-black transition cursor-pointer">
            <Plus className="h-4 w-4" /> Add Supplier
          </button>
          <button type="button" onClick={exportCSV} className="inline-flex items-center gap-1.5 rounded-lg bg-salwah-gold px-4 py-2 text-xs font-bold text-black hover:bg-salwah-gold-light transition cursor-pointer">
            <Download className="h-4 w-4" /> Export CSV
          </button>
        </div>
        {notice && <p className="mt-3 text-xs text-salwah-gold">{notice}</p>}
      </div>

      <div className="rounded-2xl border border-salwah-gold/30 bg-[#12151e] p-6 space-y-4">
        <h2 className="font-serif text-xl font-bold text-salwah-gold">Criteria Weights</h2>
        <p className="text-xs text-gray-400">Adjust priorities so weights sum to 1.00.</p>
        {([...CRITERIA, 'price'] as const).map((k) => (
          <div key={k}>
            <label className="block text-xs capitalize text-gray-300 mb-1">{k}</label>
            <input type="number" step="0.05" min={0} max={1} value={weights[k]} onChange={(e) => setWeights({ ...weights, [k]: Number(e.target.value) })} className="w-full rounded border border-salwah-gold/25 bg-black/60 px-3 py-1.5 text-sm text-white" />
          </div>
        ))}
        <p className={`text-sm font-bold ${totalWeight.toFixed(2) === '1.00' ? 'text-emerald-400' : 'text-red-400'}`}>
          Total Weight: {totalWeight.toFixed(2)} / 1.00
        </p>
      </div>
    </div>
  );
}
